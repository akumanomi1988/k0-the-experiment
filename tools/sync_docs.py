def locate(relative: str) -> Path:
    path = (ROOT / relative).resolve()
    if not path.is_relative_to(ROOT.resolve()):
        raise ValueError(f"Ruta no permitida: {relative}")
    return path


def load(relative: str):
    return json.loads(locate(relative).read_text(encoding="utf-8"))


def hashes(ptr: dict) -> tuple[str, str, dict]:
    ruleset_hash = hashlib.sha256(locate(ptr["ruleset"]).read_bytes()).hexdigest()
    manifest = load(ptr["contentManifest"])
    pairs = [[name, load("data/" + name)] for name in manifest["contentFiles"]]
    raw = json.dumps(pairs, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    catalog_hash = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    return ruleset_hash, catalog_hash, manifest


def state(ptr: dict, manifest: dict) -> dict[str, str]:
    rules = load(ptr["ruleset"])
    api = yaml.safe_load(locate(ptr["openapi"]).read_text(encoding="utf-8"))
    core_delta = load(ptr["coreDeltaSchema"])
    core_event = load(ptr["coreEventSchema"])
    core_binding = load(ptr["coreChannelSchema"])
    events = load(ptr["extensionEventSchema"])
    commands = load("data/commands.v2.json")
    version = manifest["schemaVersion"]
    if not (rules["schemaVersion"] == api["info"]["version"] == version):
        raise ValueError("Versions: ruleset, content manifest and OpenAPI design must agree")
    core = core_delta["properties"]["schemaVersion"]["const"]
    for name, obj in [("event", core_event), ("binding", core_binding)]:
        if obj["properties"]["schemaVersion"]["const"] != core:
            raise ValueError(f"Core DTO {name} disagrees about version")
    extended = {p["properties"]["schemaVersion"]["const"]
                for p in events["$defs"].values()}
    if extended != {version}:
        raise ValueError(f"SignalR extension event versions do not match active design {version}")
    choices = {x["id"]: x["precondition"] for x in commands["commands"]}
    citizens = rules["citizens"]
    v = {
        "STATUS": ptr["status"], "DOC_VERSION": version,
        "RULE_VERSION": rules["schemaVersion"], "RULE_ID": rules["rulesetId"],
        "RULE_HASH": manifest["rulesetHash"], "CONTENT_HASH": manifest["contentHash"],
        "CATALOG_COUNT": len(manifest["contentFiles"]),
        "API_VERSION": api["info"]["version"], "CORE_VERSION": core,
        "EVENT_VERSION": next(iter(extended)),
        "WORKER_SCOPE": citizens["activeHumanWorkersScope"],
        "WORKER_CAP": citizens["activeHumanWorkersSoftCap"],
        "WORKER_ORDER": citizens["humanWorkWeightOrdering"],
        "WORKER_ROTATION": citizens["humanWorkQuotaRotation"],
        "XP_POLICY": citizens["humanWorkXpEligibility"],
        "JOIN_PRE": choices["join"], "WORK_PRE": choices["work"],
        "RULESET": ptr["ruleset"], "MANIFEST": ptr["contentManifest"],
        "OPENAPI": ptr["openapi"], "CORE_DELTA": ptr["coreDeltaSchema"],
        "EXT_EVENTS": ptr["extensionEventSchema"],
        "IDENTITY": ptr["identityPolicy"], "INDEX": ptr["docsIndex"],
        "READINESS": ptr["readiness"],
    }
    for key, value in v.items():
        if not isinstance(value, (str, int)):
            raise ValueError(f"Invalid generated field {key}")
    return {key: str(value) for key, value in v.items()}


def fill(template: str, values: dict[str, str]) -> str:
    import re
    def resolve(m):
        key = m.group(1)
        if key not in values:
            raise ValueError(f"Unknown template parameter {key}")
        return values[key]
    return re.sub(r"__([A-Z_]+)__", resolve, template)


def sync(write: bool = False) -> list[str]:
    ptr = load("data/active_baseline.json")
    rh, ch, manifest = hashes(ptr)
    problems = []
    if (manifest["rulesetHash"], manifest["contentHash"]) != (rh, ch):
        problems.append("data/content_manifest.v2.json: stale canonical hashes")
        if write:
            manifest["rulesetHash"] = rh
            manifest["contentHash"] = ch
            locate(ptr["contentManifest"]).write_text(
                json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8"
            )
    replacements = state(ptr, manifest)
    for path, template in [("docs/CURRENT.md", CURRENT_TEMPLATE),
                           ("audit/RULESET_AND_CONTENT_HASHES.md", AUDIT_TEMPLATE)]:
        expected = fill(template, replacements)
        target = locate(path)
        actual = target.read_text(encoding="utf-8") if target.exists() else None
        if actual != expected:
            problems.append(path + ": generated content is stale")
            if write:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected, encoding="utf-8")
    return problems


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="Refresh source hashes and generated docs")
    parser.add_argument("--check", action="store_true", help="Fail on drift, read-only (CI default)")
    args = parser.parse_args()
    issues = sync(args.write)
    for issue in issues:
        print(("UPDATED" if args.write else "STALE") + ": " + issue)
    if issues and not args.write:
        raise SystemExit(1)
    print("PASS: active baseline hashes, versions, current documentation (write=" + str(args.write) + ")")


if __name__ == "__main__":
    main()
